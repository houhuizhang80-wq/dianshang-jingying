    function pushLuxuryProducts() {
        if (typeof PRODUCTS === 'undefined' || !Array.isArray(PRODUCTS)) return;
        const exist = {};
        PRODUCTS.forEach(p => { if (p && p.id) exist[p.id] = true; });
        LUXURY_ITEMS.forEach(row => {
            const id = row[0];
            if (exist[id]) return;
            const name = row[2];
            let originCity = '';
            if (/瑞士|陀飞轮|制表|珐琅/.test(name) || /机械腕表|腕表/.test(name)) originCity = 'geneva';
            else if (/意大利|意式|手工皮鞋/.test(name)) originCity = 'milan';
            else if (/香水|高定礼服|高定晚礼|高定西装|高定晚装/.test(name)) originCity = 'paris';
            else if (/清酒/.test(name)) originCity = 'tokyo';
            PRODUCTS.push({
                id: id,
                category: 'luxury',
                name: name,
                basePrice: Math.round(row[3] * 1.5),
                baseWeight: row[4],
                baseQuality: 94,
                procurementDays: row[5],
                unlockShopLevel: row[1],
                originCity: originCity || undefined
            });
            exist[id] = true;
        });
        PRODUCTS.forEach(p => {
            if (!p || p.category !== 'luxury' || p.originCity) return;
            const name = p.name || '';
            if (/瑞士|陀飞轮|制表|珐琅/.test(name) || /机械腕表|腕表/.test(name)) p.originCity = 'geneva';
            else if (/意大利|意式|手工皮鞋/.test(name)) p.originCity = 'milan';
            else if (/香水|高定礼服|高定晚礼|高定西装|高定晚装/.test(name)) p.originCity = 'paris';
            else if (/清酒/.test(name)) p.originCity = 'tokyo';
        });
    }

    function isProductUnlockedForShop(product, shopLevel) {
        if (!product) return false;
        const lv = Math.max(1, Number(shopLevel) || 1);
        const need = Math.max(1, Number(product.unlockShopLevel) || 1);
        if (lv < need) return false;
        if (product.ownBrandOnly) {
            try {
                const shop = (typeof gameState !== 'undefined' && gameState.state && gameState.state.shop) || null;
                if (!shop || !shop.hasOwnFactory) return false;
            } catch (_) { return false; }
        }
        return true;
    }

    /** 按店铺等级过滤后的商品目录（行情页/选品用；奢侈品不到等级不出现） */
    function getUnlockedProducts(shopLevel) {
        const lv = Math.max(1, Number(shopLevel) || 1);
        if (typeof PRODUCTS === 'undefined' || !Array.isArray(PRODUCTS)) return [];
        return PRODUCTS.filter(p => isProductUnlockedForShop(p, lv));
    }

